-- Coordinates for the overview maps: each appellation's main place, each wine country's mainland box
-- and centre, and places Cloudflare AI found for appellations that are not on the list.
alter table appellations add column if not exists lat double precision;
alter table appellations add column if not exists lon double precision;

create table if not exists countries (
  code text primary key,                 -- ISO 3166-1 alpha-2
  lon0 double precision not null, lat0 double precision not null,
  lon1 double precision not null, lat1 double precision not null,
  lon double precision not null, lat double precision not null
);
alter table countries enable row level security;
drop policy if exists countries_read on countries;
create policy countries_read on countries for select to anon, authenticated using (true);
grant select on countries to anon, authenticated;

-- Appellations not on the list, placed by Cloudflare AI; checked against the country's box
create table if not exists appellation_guesses (
  key text primary key,                  -- norm_origin(name) || '|' || country
  name text not null,
  country text not null references countries(code),
  lat double precision not null,
  lon double precision not null,
  created_at timestamptz not null default now()
);
alter table appellation_guesses enable row level security;
drop policy if exists guesses_read on appellation_guesses;
create policy guesses_read on appellation_guesses for select to anon, authenticated using (true);
grant select on appellation_guesses to anon, authenticated;

-- Hosts save a place found for an appellation; refused when it is outside the country
create or replace function save_place_guess(name text, country text, lat double precision, lon double precision)
returns boolean language plpgsql security definer set search_path = public as $$
declare c countries; k text := norm_origin(name) || '|' || upper(country);
begin
  if current_host_id() is null then raise exception 'Not a host' using errcode = '42501'; end if;
  if norm_origin(name) = '' or match_appellation(name) is not null then return false; end if;
  select * into c from countries where code = upper(country);
  if c.code is null or lat is null or lon is null
     or lat not between c.lat0 - 0.3 and c.lat1 + 0.3 or lon not between c.lon0 - 0.3 and c.lon1 + 0.3 then
    return false;
  end if;
  insert into appellation_guesses (key, name, country, lat, lon) values (k, trim(name), c.code, lat, lon)
  on conflict (key) do nothing;
  return true;
end $$;
revoke all on function save_place_guess(text, text, double precision, double precision) from public, anon;
grant execute on function save_place_guess(text, text, double precision, double precision) to authenticated;

create or replace function admin_delete_place_guess(k text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'Not an admin' using errcode = '42501'; end if;
  delete from appellation_guesses where key = k;
end $$;
revoke all on function admin_delete_place_guess(text) from public, anon;
grant execute on function admin_delete_place_guess(text) to authenticated;

-- Superadmin: which regions the wines in tastings come from, to see where a detailed map is needed
create or replace function admin_map_demand()
returns table(region text, country text, wines bigint, tastings bigint, upcoming bigint, hosts bigint, last_used timestamptz)
language plpgsql stable security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'Not an admin' using errcode = '42501'; end if;
  return query
  select coalesce(w.region, a.region) as region, coalesce(w.country, a.country) as country,
         count(distinct w.id), count(distinct t.id),
         count(distinct t.id) filter (where t.starts_at is null or t.starts_at >= now() - interval '1 day'),
         count(distinct t.host_id), max(t.created_at)
  from tasting_wines tw
  join tastings t on t.id = tw.tasting_id
  join wines w on w.id = tw.wine_id
  left join appellations a on a.id = w.appellation_id
  where coalesce(w.region, a.region) is not null
  group by 1, 2
  order by 5 desc, 4 desc, 3 desc;
end $$;
revoke all on function admin_map_demand() from public, anon;
grant execute on function admin_map_demand() to authenticated;
